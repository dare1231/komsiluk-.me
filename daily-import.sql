create table if not exists public.daily_import_runs (
  id bigint generated by default as identity primary key,
  run_date date not null unique,
  added_count integer not null default 0,
  deleted_count integer not null default 0,
  cities text[] not null default '{}',
  created_at timestamptz not null default now()
);
create index if not exists daily_import_runs_created_at_idx on public.daily_import_runs (created_at desc);
alter table public.daily_import_runs enable row level security;
